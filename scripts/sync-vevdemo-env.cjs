#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const DEFAULT_ORIGIN_ENV = '/Users/mark/Documents/key/origin.env.local';
const ORIGIN_ENV_FILE = process.env.ORIGIN_ENV_FILE || DEFAULT_ORIGIN_ENV;
const REPO_ROOT = path.resolve(__dirname, '..');
const VEVDemo_ROOT = path.join(REPO_ROOT, 'vevdemo-1.0.6');
const FE_ENV_LOCAL = path.join(VEVDemo_ROOT, 'fe', '.env.local');

const FE_KEYS = [
  'VITE_DEV_HOST',
  'VITE_DEV_PORT',
  'VITE_VEVDEMO_API_BASE',
  'VITE_VEV_REGION',
  'VITE_VEV_VOD_HOST',
  'VITE_VEV_PROJECT_ID',
  'VITE_VEV_GROUP_ID',
  'VITE_VEV_DEFAULT_CLASSIFICATION_ID',
  'VITE_VEV_VOD_ACCOUNT_ID',
  'VITE_VEV_UPLOAD_APP_ID',
  'VITE_VEV_UPLOAD_WORKFLOW_TEMPLATE_ID',
];

function parseEnv(text) {
  const result = {};
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const match = rawLine.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!match) continue;
    let value = match[2] || '';
    const commentIndex = value.search(/\s#/);
    if (commentIndex >= 0) value = value.slice(0, commentIndex).trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    result[match[1]] = value;
  }
  return result;
}

function quote(value) {
  return JSON.stringify(String(value ?? ''));
}

function writeEnvFile(filePath, keys, env, header) {
  const lines = [
    '# Generated by scripts/sync-vevdemo-env.cjs.',
    `# Source: ${ORIGIN_ENV_FILE}`,
    '# Do not edit this file directly; update the external origin.env.local instead.',
    header,
    '',
  ];
  for (const key of keys) {
    lines.push(`${key}=${quote(env[key] || '')}`);
  }
  fs.writeFileSync(filePath, lines.join('\n') + '\n');
}

if (!fs.existsSync(ORIGIN_ENV_FILE)) {
  console.error(`[sync-vevdemo-env] missing origin env file: ${ORIGIN_ENV_FILE}`);
  process.exit(1);
}

const env = parseEnv(fs.readFileSync(ORIGIN_ENV_FILE, 'utf8'));
if (!env.VITE_VEVDEMO_API_BASE && env.VEVDEMO_API_URL) env.VITE_VEVDEMO_API_BASE = env.VEVDEMO_API_URL;

writeEnvFile(FE_ENV_LOCAL, FE_KEYS, env, '# VevDemo frontend Vite env.');

const missingFe = FE_KEYS.filter((key) => !env[key] && key !== 'VITE_VEV_DEFAULT_CLASSIFICATION_ID');
console.log(`[sync-vevdemo-env] wrote ${FE_ENV_LOCAL}`);
if (missingFe.length) console.warn(`[sync-vevdemo-env] missing frontend keys: ${missingFe.join(', ')}`);
